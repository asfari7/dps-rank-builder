function normalizeImportedData(data) {
  if (!data || !Array.isArray(data.teams))
    throw new Error("Format JSON tidak valid.")
  const importedTeams = data.teams.slice(0, maxTeams).map((team) => ({
    dps: Number(team.dps) || 0,
    cost: Number.isFinite(Number(team.cost))
      ? Number(team.cost)
      : Array.isArray(team.members)
        ? team.members.reduce(
            (total, member) => total + Number(member[3] || 0),
            0,
          )
        : 0,
    members: Array.isArray(team.members)
      ? team.members
          .slice(0, 4)
          .map((member) => {
            const charId = member[0] || "skirk"
            const charType = characterWeaponTypeMap[charId] || "sword"
            const validWeps = weaponOptionsByType[charType] || weaponOptions
            let wepId = member[1] || validWeps[0][0]
            if (weaponTypeMap[wepId] !== charType) {
              wepId = validWeps[0][0]
            }
            return [
              charId,
              wepId,
              member[2] || "gladiators-finale",
              Number(member[3]) || 0,
              Math.max(1, Math.min(5, Number(member[4]) || 1)),
            ]
          })
      : [],
  }))
  return {
    accountName:
      typeof data.accountName === "string" ? data.accountName : "Akunku",
    teams: importedTeams,
  }
}
